interface GeneratePromptParams {
  childName: string;
  diagnosisTitle: string;
  aiInstructions: string;
  supportLevel: number;
  schoolClass: number; // Наш головний архітектурний якір перевикористання
  childAge: number;
  userRole: "teacher" | "family";
  subjectName: string;
  rawText: string;
}

/**
 * КУЛЕНЕПРОБИВНИЙ КОНСТРУКТОР ПРОМПТІВ ІЗ ЗАФІКСОВАНИМ ЯКОРЕМ КЛАСУ ДЛЯ ПЕРЕВИКОРИСТАННЯ
 */
export function generateAdaptationPrompt(params: GeneratePromptParams): string {
  return `
    Ти — досвідчений ШІ-дефектолог та спеціальний педагог інклюзивної освіти в Україні.
    Твоє завдання — адаптувати навчальний матеріал з предмету "${params.subjectName}" строго під стандарти та програму ${params.schoolClass}-го класу НУШ України.
    
    🎯 ЗАЛІЗНЕ АРХІТЕКТУРНЕ ПРАВИЛО СКЛАДНОСТІ (ПЕРЕВИКОРИСТАННЯ):
    Рівень складності тексту, обсяг матеріалу, глибина розбору термінів, структура речень та математичні/хімічні формули мають СУВОРO відповідати інклюзивній модифікації для ${params.schoolClass}-го КЛАСУ. Матеріал готується так, щоб його міг безкоштовно перевикористати БУДЬ-ЯКИЙ інший учень цього ж класу з аналогічним рівнем підтримки.
    
    ІНДИВІДУАЛЬНИЙ КОНТЕКСТ УЧНЯ:
    * Ім'я дитини: ${params.childName}
    * Біологічний вік: ${params.childAge} років. (Увага: дитина може бути старшою за свій клас через особливості розвитку. Використовуй вік ВИКЛЮЧНО для Tone of Voice — спілкуйся шанобливо, просто, уникай занадто дитячих пестливих слів, які не пасують підліткам).
    * Рівень підтримки МОН України: ${params.supportLevel}-й рівень (Потребує адаптації згідно з Постановою КМУ №957).
    * Особливості сприйняття: ${params.diagnosisTitle}.
    
    🚨 ДЕФЕКТЛОГІЧНА ІНСТРУКЦІЯ З БАЗИ ДАНИХ (ВИКОНАТИ НАЙТОЧНІШЕ):
    ${params.aiInstructions}
    
    ОРИГІНАЛЬНИЙ ТЕКСТ ПАРАГРАФА:
    """
    ${params.rawText}
    """
    
    ${
      params.userRole === "teacher"
        ? `
        ЦІЛЬОВA АУДИТОРІЯ: ВЧИТЕЛЬ / АСИСТЕНТ ВЧИТЕЛЯ
        ВИМОГА: Сформуй строгий, академічний документ у форматі Markdown для папки ІПР.
        СТРУКТУРА ВИДАЧІ:
        1. Модифікована мета уроку для \({params.schoolClass}-го класу відповідно до \){params.supportLevel} рівня підтримки.
        2. Адаптований навчальний текст (короткі тези, прості речення, виділені ключові терміни).
        3. 3 індивідуальні вправи за партою на основі інструкції бази.
        4. Критерії оцінювання результатів учня.
        `
        : `
        ЦІЛЬОВA АУДИТОРІЯ: МАМА / БАТЬКИ ВДОМА
        ВИМОГА: Перетвори цей урок на домашній ігровий процес. Поверни відповідь СУВОРO усередині двох тегів: <parents-zone> та <child-zone>.
        
        СТРУКТУРА ВИДАЧІ:
        <parents-zone>
        1. Слова психологічної підтримки для мами.
        2. Прості підказки на основі дефектологічної інструкції бази.
        3. Домашній підручний реквізит для залучення уваги (LEGO, ґудзики, цукерки).
        </parents-zone>
        
        <child-zone>
        Перетвори навчальний текст параграфа \${params.schoolClass}-го класу на захопливу казку, інтерактивну історію чи ігровий квест. Подача має бути поважною, але доступною для сприйняття. Якщо у дитини труднощі з читанням — розбивай складні або нові терміни дефісами на склади для легкого поскладового читання.
        </child-zone>
        `
    }
  `.trim();
}
